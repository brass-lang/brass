"""The two services the desk reaches outside itself. The host implements them; every entry point receives the ones it needs."""
from typing import Protocol, Sequence

from .advances import Advance
from .audit import Entry
from .ids import Badge, DepartmentId, Period, ReportId, TripId
from .reports import Report
from .staff import Department, Staff
from .trips import Trip


class Store(Protocol):
    def staff(self, badge: Badge) -> Staff: ...                                   # Failure(NOT_FOUND) when missing
    def report(self, id: ReportId) -> Report: ...
    def department(self, id: DepartmentId) -> Department: ...
    def reports_for(self, department: DepartmentId, period: Period) -> Sequence[Report]: ...
    def submitted_reports(self) -> Sequence[Report]: ...
    def period_closed(self, period: Period) -> bool: ...
    def next_id(self) -> ReportId: ...
    def save_report(self, report: Report) -> None: ...
    def append_audit(self, entry: Entry) -> None: ...
    def close_period(self, period: Period) -> None: ...
    def advance(self, id: ReportId) -> Advance: ...
    def advances_for(self, department: DepartmentId, period: Period) -> Sequence[Advance]: ...
    def paid_advances(self) -> Sequence[Advance]: ...
    def save_advance(self, advance: Advance) -> None: ...
    def trip(self, id: TripId) -> Trip: ...                                       # Failure(NOT_FOUND) when missing
    def trips_for(self, department: DepartmentId, period: Period) -> Sequence[Trip]: ...
    def trips_in(self, period: Period) -> Sequence[Trip]: ...                     # every trip there; at most 1,000
    def save_trip(self, trip: Trip) -> None: ...


class Ledger(Protocol):
    def pay(self, badge: Badge, amount: int, key: ReportId) -> str: ...          # returns the ledger's reference; Failure(UNAVAILABLE) when down
