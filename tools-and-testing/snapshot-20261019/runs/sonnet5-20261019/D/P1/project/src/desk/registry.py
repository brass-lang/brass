"""The grown desk's own host access. The host implements it; entry points that need it receive it as `reg`. New ids still come from `Store.next_id()`."""
from typing import Protocol, Sequence

from .ids import Badge, DepartmentId, Money, Period, ReportId
from .records import (CardLimit, CardTxn, CostCenter, CostCenterId, Delegation, DelegationId, Entity, EntityId,
                      ExceptionId, PoId, PolicyException, PurchaseOrder, TxnId, Vendor, VendorId)


class Registry(Protocol):
    def vendor(self, id: VendorId) -> Vendor: ...                                  # Failure(NOT_FOUND) when missing
    def po(self, id: PoId) -> PurchaseOrder: ...
    def pos_for(self, department: DepartmentId, period: Period) -> Sequence[PurchaseOrder]: ...
    def txn(self, id: TxnId) -> CardTxn: ...
    def txns_for(self, period: Period) -> Sequence[CardTxn]: ...
    def delegation(self, id: DelegationId) -> Delegation: ...
    def delegations_from(self, badge: Badge) -> Sequence[Delegation]: ...
    def cost_center(self, id: CostCenterId) -> CostCenter: ...
    def departments_of(self, cost_center: CostCenterId) -> Sequence[DepartmentId]: ...
    def entity(self, id: EntityId) -> Entity: ...
    def allowance(self, department: DepartmentId, period: Period) -> Money: ...      # the PO allowance
    def pos_of_vendor(self, vendor: VendorId) -> Sequence[PurchaseOrder]: ...
    def card_limit(self, badge: Badge) -> CardLimit: ...                           # Failure(NOT_FOUND) when none is set
    def departments(self) -> Sequence[DepartmentId]: ...
    def exception(self, id: ExceptionId) -> PolicyException: ...
    def exceptions_for(self, report: ReportId) -> Sequence[PolicyException]: ...
    def save_po(self, po: PurchaseOrder) -> None: ...
    def save_txn(self, txn: CardTxn) -> None: ...
    def save_delegation(self, d: Delegation) -> None: ...
    def save_vendor(self, v: Vendor) -> None: ...
    def save_card_limit(self, l: CardLimit) -> None: ...
    def save_exception(self, e: PolicyException) -> None: ...
