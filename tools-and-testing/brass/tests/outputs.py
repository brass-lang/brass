"""Regenerate OUTPUTS.md: real brass output for every command, on a copy of the stage 2 tree (still `.keel`: it is frozen at its tag), with one planted
fault per rejection. usage: python3 tests/outputs.py"""
import os, shutil, subprocess, sys
from pathlib import Path
V = Path("/home/author/work/keel/validation")
BRASS = V / "proxy/bin/brass"
import tempfile
SC = Path(tempfile.mkdtemp())
OUT = Path(__file__).resolve().parents[1] / "OUTPUTS.md"
BASE = V / "14-scale/stage2/start/keel"
CONTRACT = (V / "14-scale/materials/contract.grown.txt").read_text()

def fresh(name):
    p = SC / name
    if p.exists(): shutil.rmtree(p)
    shutil.copytree(V / "14-scale/stage2/start/keel", p)
    (p / "host-contract.txt").write_text(CONTRACT)
    return p

def plant(p, f, old, new):
    q = p / "src/desk" / f; s = q.read_text(); assert s.count(old) == 1, (f, old); q.write_text(s.replace(old, new))

def run(p, args, lean="3", stdin=None, limit=40):
    env = dict(os.environ, BRASS_PROJECT=str(p), BRASS_SRC="desk", BRASS_NO_LOG="1", BRASS_BASELINE=str(BASE))
    env.pop("BRASS_LEAN", None)
    if lean: env["BRASS_LEAN"] = lean
    r = subprocess.run([sys.executable, str(BRASS)] + args, env=env, input=stdin, capture_output=True, text=True)
    out = (r.stdout + r.stderr).rstrip().replace(str(p), "<project>")
    ls = out.splitlines()
    if len(ls) > limit: ls = ls[:limit] + [f"… ({len(ls) - limit} more lines)"]
    return "\n".join(ls)

HEAD = """# brass: every kind of output

Real output, regenerated by `tests/outputs.py`. The project is a copy of the stage 2 Brass tree
(`../14-scale/stage2/start/keel/`), which is also the baseline, so "touched" lists only what a planted fault changed.
Each rejection below comes from one planted fault, named above its block. Long outputs are trimmed.

Two known gaps show here: the effect check misses a write followed by `if … else Err(…)` at the same indent, and
"touched" marks every entry point in an edited file as changed, not only the one edited. Both are in `BRASS.md`.

"""
sections = []
def add(title, why, cmd, out):
    sections.append(f"### {title}\n\n{why}\n\n```text\n$ {cmd}\n{out}\n```\n")

clean = fresh("clean")
sections.append("## Lean mode: what sessions use (`BRASS_LEAN=3`)\n")
add("Usage", "Any unknown command answers with this.", "brass help", run(clean, ["help"]))
add("show: the whole interface", "Every module's declarations, numbered, in one call. Trimmed here.", "brass show", run(clean, ["show"], limit=25))
add("show several declarations with bodies", "", "brass show lines.total payment.pay", run(clean, ["show", "lines.total", "payment.pay"]))
add("show --body: whole files", "Several modules in one call. Trimmed here.", "brass show --body lines audit", run(clean, ["show", "--body", "lines", "audit"], limit=25))
add("info: who uses a declaration", "", "brass info lines.budgeted_total", run(clean, ["info", "lines.budgeted_total"]))
add("check: clean", "Structure, examples, scenarios, host contract, converters, effect order, and every entry point touched against the baseline. Ends in `done`.", "brass check", run(clean, ["check"], limit=60))

p = fresh("structure"); plant(p, "payment.keel", "ledger.pay(r.badge, lines.total(r.lines), r.id)?", "ledger.pay(r.badge, lines.totl(r.lines), r.id)?")
add("check: a structural rejection", "Planted: a call to `lines.totl`, which does not exist.", "brass check", run(p, ["check"]))
p = fresh("example"); plant(p, "lines.keel", "receipt: false }]) == 3000", "receipt: false }]) == 3500")
add("check: a failing example", "Planted: `total`'s example expects 3500; the body gives 3000.", "brass check", run(p, ["check"]))
p = fresh("effects"); plant(p, "payment.keel", "        store.save_report(reports.pay(r, reference))?\n        store.append_audit(audit.report_entry(who.badge, r.id, reports.ReportStatus.Approved, reports.ReportStatus.Paid, \"paid\"))?\n", "        store.save_report(reports.pay(r, reference))?\n        store.append_audit(audit.report_entry(who.badge, r.id, reports.ReportStatus.Approved, reports.ReportStatus.Paid, \"paid\"))?\n        if lines.total(r.lines) > 5000000 then Err(FailureCode.Conflict, \"over the payment limit\") else Ok(Done)\n")
add("check: a write before a possible refusal", "Planted: `pay` saves the paid report, then refuses a payment over a limit; the save stays behind.", "brass check", run(p, ["check"]))
p = fresh("effects-miss"); plant(p, "payment.keel", "      if r is reports.Approved then\n        let reference: Text = ledger.pay(r.badge, lines.total(r.lines), r.id)?", "      store.save_report(r)?\n      if r is reports.Approved then\n        let reference: Text = ledger.pay(r.badge, lines.total(r.lines), r.id)?")
add("check: a write before a refusal the check misses (known gap)", "Planted: `pay` saves the report, then `if r is reports.Approved then … else Err(Conflict)` refuses. The check reads that `else` as another path and stays silent. Recorded in `BRASS.md`; not fixed.", "brass check", run(p, ["check"], limit=12))
p = fresh("host"); (p / "host-contract.txt").write_text(CONTRACT.replace("Store.append_audit\n", ""))
add("check: an operation the host does not provide", "Planted: `Store.append_audit` removed from the host contract.", "brass check", run(p, ["check"]))
p = fresh("conv"); plant(p, "audit.keel", "    example of_advance(advances.AdvanceStatus.Paid) == Step.Paid\n", "")
plant(p, "audit.keel", "example of_report(reports.ReportStatus.Rejected) == Step.Rejected", "example of_report(reports.ReportStatus.Rejected) == Step.ChangesRequested")
add("check: converter coverage", "Planted: `of_advance` loses its example for `Paid`; one `of_report` example expects the wrong step.", "brass check", run(p, ["check"]))

p = fresh("apply")
good = "@@@ edit src/desk/lines.keel\n@@@ find\n  fn total(ls) =\n    let sum: Int = 0\n@@@ replace\n  fn total(ls) =\n    let sum: Int = 0\n@@@ end\n"
bad = good + "@@@ edit src/desk/payment.keel\n@@@ find\nthis text is not in the file\n@@@ replace\nx\n@@@ end\n"
add("apply --dry", "Matches every block, writes nothing.", "brass apply --dry <<'PATCH' … PATCH", run(p, ["apply", "--dry"], stdin=good))
add("apply: a block that does not match", "All or nothing: one block misses, so nothing is written.", "brass apply <<'PATCH' … PATCH", run(p, ["apply"], stdin=bad))
add("apply: a patch that is not closed", "", "brass apply <<'PATCH' … PATCH", run(p, ["apply"], stdin="@@@ edit src/desk/lines.keel\n@@@ find\n  fn total(ls) =\n"))
add("apply: written, then the full check", "", "brass apply <<'PATCH' … PATCH", run(p, ["apply"], stdin=good, limit=30))
add("summary", "Each entry point in check order: refusals, host calls, states entered. Trimmed here.", "brass summary", run(clean, ["summary"], limit=30))

sections.append("## Full mode: the older query commands (no `BRASS_LEAN`)\n\nStill there; trials since lean mode do not use them.\n")
for args, why in [(["info"], "The system map."), (["info", "--names"], ""), (["info", "--holds"], ""), (["info", "lines"], "A module's interface with tiers."),
                  (["info", "lines.total", "--if-changed"], ""), (["info", "review.may_act", "--established-by"], ""),
                  (["info", "payment.pay", "--at", "21"], "Facts in scope at a body line."), (["info", "payment.pay", "--effects"], ""),
                  (["info", "--if", "lines.total = fn total(ls: Lines) -> Int where it >= 1"], "A static what-if."),
                  (["info", "--forms"], ""), (["review", "payment"], ""), (["changes"], "Against the baseline tree."),
                  (["run", "lines.total", '[{ category: ids.Category.Feed, amount: 1000, description: "a", receipt: false }]'], ""),
                  (["check"], "Level 1 structure, with the program summary when clean."), (["check", "--examples"], ""), (["show", "lines.total"], "")]:
    add("brass " + " ".join(a if " " not in a else "'" + a + "'" for a in args), why, "brass " + " ".join(args), run(clean, args, lean=None, limit=20))

OUT.write_text(HEAD + "\n".join(sections))
shutil.rmtree(SC)
print(len(sections), "sections")
